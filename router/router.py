"""Маршрутизатор контуров (приложение A, §8 — дерево классов).

Вход — описание требования. Выход — класс:
  A   мягкое   -> открытый контур (ИИ предлагает)
  B1  жёсткое, есть дешёвая надёжная проверка -> детерминированная проверка
  B2  жёсткое, проверки нет/дорого -> оценка с честной пометкой
  B3  жёсткое, проверка есть, но правило может устареть -> проверка + ревизия
"""

LABELS = {
    "A":  "открытый контур (ИИ предлагает)",
    "B1": "детерминированная проверка (программа-сторож)",
    "B2": "оценка с честной пометкой (conformal)",
    "B3": "проверка + ревизия правила (эталонные тесты)",
}


def route(req: dict) -> str:
    if req.get("kind") == "soft":
        return "A"
    # жёсткое требование:
    if not req.get("has_cheap_oracle"):
        return "B2"
    if req.get("rule_may_be_stale"):
        return "B3"
    return "B1"


if __name__ == "__main__":
    demo = [
        {"name": "лимит давления", "kind": "hard", "has_cheap_oracle": True},
        {"name": "межузловой инвариант", "kind": "hard", "has_cheap_oracle": False},
        {"name": "соответствие регламенту", "kind": "hard",
         "has_cheap_oracle": True, "rule_may_be_stale": True},
        {"name": "экономия энергии", "kind": "soft"},
    ]
    for r in demo:
        c = route(r)
        print(f"{r['name']:30} -> {c:3}  {LABELS[c]}")
